_MARK = re.compile(r"\[\[(.+?)\]\]")


def plain(text):
    return _MARK.sub(r"\1", text)


def split_marks(text):
    """Вернёт [(фрагмент, это_пример)], чтобы подсветить числа-примеры."""
    out, pos = [], 0
    for m in _MARK.finditer(text):
        if m.start() > pos:
            out.append((text[pos:m.start()], False))
        out.append((m.group(1), True))
        pos = m.end()
    if pos < len(text):
        out.append((text[pos:], False))
    return out


def words(slide_numbers):
    return sum(len(plain(p).split()) for n in slide_numbers for p in SLIDES[n]["speech"])


def speaker_slides(speaker):
    return [n for n in sorted(SLIDES) if SLIDES[n]["speaker"] == speaker]


def ranges(nums):
    """[1,2,3,7,8] -> '1–3, 7–8'"""
    out, start, prev = [], None, None
    for n in nums + [None]:
        if start is None:
            start = prev = n
        elif n is not None and n == prev + 1:
            prev = n
        else:
            out.append(f"{start}" if start == prev else f"{start}–{prev}")
            start = prev = n
    return ", ".join(out)
